// Command gen-mcp-tools writes the MCP tool reference table.
package main

import (
	"fmt"
	"os"
	"strings"

	"github.com/martianzhang/aigc-cli/internal/mcp"
)

func main() {
	var b strings.Builder
	b.WriteString("# MCP Tool Catalog\n\n")
	b.WriteString("<!-- Generated by `make docs-gen`; do not edit by hand. -->\n\n")
	b.WriteString("| Tool | Description |\n")
	b.WriteString("|---|---|\n")
	for _, tool := range mcp.ToolCatalog() {
		desc := strings.ReplaceAll(tool.Description, "|", `\|`)
		desc = strings.ReplaceAll(desc, "\n", " ")
		fmt.Fprintf(&b, "| `%s` | %s |\n", tool.Name, desc)
	}
	if _, err := os.Stdout.WriteString(b.String()); err != nil {
		os.Exit(1)
	}
}
