package detect

import (
	"fmt"
	"io"
	"os"

	"github.com/spf13/cobra"
)

var detectCmd = &cobra.Command{
	Use:          "detect <file...>",
	Short:        "Detect watermarks, metadata, and AIGC signals in images",
	SilenceUsage: true,
	Long: `AIGC detection and research tool — fuses multiple signals to judge whether an
image was generated by AI.

First use: run 'aigc-cli detect init' to download the ONNX detection model.

Signals:
  - C2PA Content Credentials (tamper-evident provenance metadata)
  - TC260 AIGC label (China national standard GB 45438-2025)
  - SynthID invisible watermark (inferred from the C2PA issuer)
  - FFT spectral analysis (pixel-level frequency artifacts)
  - ONNX model inference (model must be downloaded)
  - Visible AI watermark detection (requires a watermark learned via --learn-watermark)

All signals are fused into a single AIGen confidence score (with emoji).

⚠️ Compliance
This project ships no vendor watermark-removal capability. --remove-watermark
only affects watermarks you learned yourself via --learn-watermark; you are
responsible for using it in compliance with applicable laws.

--add-watermark only creates test samples for removal algorithms; it injects
no metadata.

Supported formats: PNG, JPEG, WebP, GIF, BMP.`,
	Example: `  aigc-cli detect photo.png                     # multi-signal AIGC report
  aigc-cli detect a.png b.jpg c.webp            # scan several files
  aigc-cli detect photo.png --preview           # open in viewer after scanning
  aigc-cli detect photo.png --remove-watermark  # remove a learned watermark`,
	RunE: runDetect,
}

var detectPreview bool
var detectRemoveWM bool
var detectAlphaMap bool // --alpha-map: use learned alpha map removal instead of AI
var detectMiGAN bool    // --mi-gan: force MI-GAN AI removal
var detectAddWM bool
var detectWmProducer string
var detectWatermarkBox string     // --watermark-box: manual position "x,y,w,h"
var detectLearnWM string          // --learn-watermark {name}
var detectLearnStrategy string    // --strategy for learn-watermark
var detectNativeWidth int         // --native-width for imported alpha maps
var detectMarginXFrac float64     // --margin-x-frac
var detectMarginYFrac float64     // --margin-y-frac
var detectDetectThreshold float64 // --detect-threshold
var detectCropWM string           // --crop-watermark [WxH]

func runDetect(cmd *cobra.Command, args []string) error {
	// --learn-watermark: learn a custom watermark from seed images
	if detectLearnWM != "" {
		return runLearnWatermark(detectLearnWM)
	}

	if len(args) > 0 {
		return detectFiles(args, "")
	}

	stat, err := os.Stdin.Stat()
	if err != nil || (stat.Mode()&os.ModeCharDevice) != 0 {
		return fmt.Errorf("no files specified: pass file paths as arguments or pipe file data to stdin")
	}

	data, err := io.ReadAll(os.Stdin)
	if err != nil {
		return fmt.Errorf("failed to read stdin: %w", err)
	}
	if len(data) == 0 {
		return fmt.Errorf("no data read from stdin")
	}

	tmpFile, err := os.CreateTemp("", "aigc-cli-detect-*")
	if err != nil {
		return fmt.Errorf("failed to create temp file: %w", err)
	}
	defer os.Remove(tmpFile.Name())

	if _, err := tmpFile.Write(data); err != nil {
		tmpFile.Close()
		return fmt.Errorf("failed to write temp file: %w", err)
	}
	tmpFile.Close()

	return detectFiles([]string{tmpFile.Name()}, "(stdin)")
}

func init() {
	detectCmd.Flags().BoolVar(&detectPreview, "preview", false, "open image in system viewer after detection")
	detectCmd.Flags().BoolVar(&detectRemoveWM, "remove-watermark", false, "remove visible AI watermarks (uses MI-GAN AI inpainting; on failure, try --alpha-map or --producer)")
	detectCmd.Flags().BoolVar(&detectAlphaMap, "alpha-map", false, "use learned alpha map removal (classical, fallback when MI-GAN fails)")
	detectCmd.Flags().BoolVar(&detectMiGAN, "mi-gan", false, "force MI-GAN AI inpainting removal (default algorithm)")
	detectCmd.Flags().BoolVar(&detectAddWM, "add-watermark", false, "add a visible AI watermark for testing removal (no metadata injected)")
	detectCmd.Flags().StringVar(&detectWmProducer, "producer", "",
		`watermark producer name learned via --learn-watermark, e.g. "gemini"`)
	detectCmd.Flags().StringVar(&detectWatermarkBox, "watermark-box", "",
		`manual watermark position "w,h" or "x,y,w,h" (e.g. "200,60" for bottom-right, "800,900,200,60" for absolute)`)
	detectCmd.Flags().StringVar(&detectWatermarkBox, "wmb", "",
		"shorthand for --watermark-box")
	detectCmd.Flags().StringVar(&detectLearnWM, "learn-watermark", "", `learn a watermark from seed images in ~/.config/aigc-cli/watermark/
  {name}.black.png + {name}.gray.png (single pair)
  {name}.2.black.png + {name}.2.gray.png (2nd pair, averaged for lower noise)
  {name}.3.black.png + ... (any number of pairs, all averaged)`)
	detectCmd.Flags().StringVar(&detectLearnStrategy, "strategy", "alpha_blend",
		`removal strategy: "alpha_blend" (default, reverse alpha blending) or "inpaint" (texture fill for badge-type watermarks)`)
	detectCmd.Flags().IntVar(&detectNativeWidth, "native-width", 1024,
		"native image width the alpha map was calibrated at (for imported alpha maps)")
	detectCmd.Flags().Float64Var(&detectMarginXFrac, "margin-x-frac", 0.02,
		"right margin fraction of image width (for imported alpha maps)")
	detectCmd.Flags().Float64Var(&detectMarginYFrac, "margin-y-frac", 0.02,
		"bottom margin fraction of image width (for imported alpha maps)")
	detectCmd.Flags().Float64Var(&detectDetectThreshold, "detect-threshold", 0.25,
		"minimum NCC confidence for detection (for imported alpha maps)")
	detectCmd.Flags().StringVar(&detectCropWM, "crop-watermark", "",
		`crop to remove watermarks: "auto" (default), target "WxH" (e.g. "1920x1080"), or keep ratio "n%%" (e.g. "97%%")`)
}

// Cmd returns the detect command tree.
func Cmd() *cobra.Command { return detectCmd }
